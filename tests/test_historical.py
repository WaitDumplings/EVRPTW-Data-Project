"""Historical verification must use saved code and leave original files intact."""

import json
from pathlib import Path

import pytest

from evrptw_cle.cli import main
from evrptw_cle.historical import inspect_history, verify_historical
from evrptw_cle.util import sha256_file
from evrptw_cle.workflow import verify_output


def frozen_fixture(tmp_path):
    root = tmp_path / "old-cle"
    snapshot = root / "code_snapshot"
    package = snapshot / "src/evrptw_cle"
    package.mkdir(parents=True)
    (snapshot / "scripts").mkdir()
    (snapshot / "pyproject.toml").write_text("# saved project\n")
    (package / "__init__.py").write_text("")
    # The subprocess must import this old implementation, not the installed
    # current evrptw_cle package (which would require full geographic data).
    (package / "cle_validation.py").write_text('''
import hashlib
import json
from pathlib import Path
def sha256_file(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def verify_city_cle(city, report_path):
    manifest = Path(city) / "cle_manifest.json"
    sources = json.loads(manifest.read_text())["sources"]
    for name in ["parameter_contract", "native_source"]:
        reference = sources[name]
        path = Path(reference["path"])
        if not path.is_file() or sha256_file(path) != reference["sha256"]:
            raise ValueError("Changed original input: " + name)
    result = dict(passed=True, summary={"saved_version": True},
        verified_terminal_paths=7,
        cle_manifest_sha256=hashlib.sha256(manifest.read_bytes()).hexdigest(),
        verifier_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest())
    Path(report_path).write_text(json.dumps(result))
    return result
''')
    (snapshot / "scripts/verify_stage1.py").write_text('''
import argparse
from evrptw_cle.cle_validation import verify_city_cle
p = argparse.ArgumentParser()
p.add_argument("--root")
p.add_argument("--inventory")
p.add_argument("--city")
p.add_argument("--report")
a = p.parse_args()
verify_city_cle(a.root + "/cities/" + a.city, report_path=a.report)
''')
    inventory = tmp_path / "original-inventory.json"
    inventory.write_text('{"cities":{"oldcity":{}}}')
    policy_name = "charging_parameter_contract_v1.json"
    (snapshot / "configs").mkdir()
    policy = snapshot / "configs" / policy_name
    policy.write_text("original frozen policy bytes")
    newer_policy = tmp_path / "current-project/configs" / policy_name
    newer_policy.parent.mkdir(parents=True)
    newer_policy.write_text("changed current policy; do not edit this file")
    native = tmp_path / "native.bin"
    native.write_bytes(b"native geographic source")
    city = root / "cities/oldcity"
    city.mkdir(parents=True)
    (city / "cle_manifest.json").write_text(json.dumps(dict(
        policy_hashes={policy_name: sha256_file(policy)}, sources=dict(
            frozen_inventory=dict(path=str(inventory), sha256=sha256_file(inventory)),
            parameter_contract=dict(path=str(newer_policy), sha256=sha256_file(policy)),
            native_source=dict(path=str(native), sha256=sha256_file(native))))))
    (city / "cle_verification.json").write_text(json.dumps(dict(
        passed=True, cle_manifest_sha256=sha256_file(city / "cle_manifest.json"))))
    receipt = dict(schema="evrptw_stage1_internal_freeze_v1", frozen=True,
                   generated_utc="2026-10-28T01:01:37Z", cities=dict(oldcity=dict(
                       cle_manifest_sha256=sha256_file(city / "cle_manifest.json"),
                       verification_sha256=sha256_file(city / "cle_verification.json"))),
                   code_snapshot={str(p.relative_to(snapshot)): sha256_file(p)
                                  for p in snapshot.rglob("*") if p.is_file()})
    (root / "stage1_freeze.json").write_text(json.dumps(receipt))
    return root


def all_files(root):
    return {str(p.relative_to(root)): p.read_bytes() for p in root.rglob("*") if p.is_file()}


def test_historical_subprocess_uses_original_version_without_touching_cohort(tmp_path):
    root = frozen_fixture(tmp_path)
    before = all_files(root)
    reports = tmp_path / "fresh-audit"
    result = verify_historical(root, report_dir=reports)
    assert result["passed"] and result["city_count"] == 1
    assert result["cities"]["oldcity"]["summary"] == {"saved_version": True}
    assert result["cities"]["oldcity"]["verified_terminal_paths"] == 7
    aliases = result["policy_resource_aliases"]
    original = str(tmp_path / "current-project/configs/charging_parameter_contract_v1.json")
    assert aliases[original]["resolved_path"] == str(
        root / "code_snapshot/configs/charging_parameter_contract_v1.json")
    assert str(tmp_path / "native.bin") not in aliases
    assert Path(original).read_text() == "changed current policy; do not edit this file"
    assert (reports / "oldcity.json").is_file()
    assert all_files(root) == before
    assert inspect_history(root)["metadata_bindings_verified"]


def test_changed_snapshot_fails_before_running_or_creating_reports(tmp_path):
    root = frozen_fixture(tmp_path)
    (root / "code_snapshot/src/evrptw_cle/cle_validation.py").write_text("changed")
    reports = tmp_path / "new-audit"
    with pytest.raises(ValueError, match="implementation file changed"):
        verify_historical(root, report_dir=reports)
    assert not reports.exists()


def test_policy_relocation_does_not_bypass_raw_source_hash_check(tmp_path):
    root = frozen_fixture(tmp_path)
    (tmp_path / "native.bin").write_bytes(b"changed source")
    reports = tmp_path / "fresh-audit"
    with pytest.raises(RuntimeError, match="Historical verification failed"):
        verify_historical(root, report_dir=reports)
    assert "Changed original input: native_source" in (reports / "oldcity.log").read_text()
    result = json.loads((reports / "stage1_verification.json").read_text())
    assert result["state"] == "failed" and not result["passed"]


def test_historical_reports_and_default_verify_never_write_frozen_root(tmp_path):
    root = frozen_fixture(tmp_path)
    before = all_files(root)
    with pytest.raises(ValueError, match="outside"):
        verify_historical(root, report_dir=root / "reaudit")
    with pytest.raises(ValueError, match="--historical"):
        verify_output(root)
    assert all_files(root) == before


def test_selected_historical_city_must_be_in_original_receipt(tmp_path):
    root = frozen_fixture(tmp_path)
    with pytest.raises(ValueError, match="unique cities"):
        verify_historical(root, cities=["another"])


def test_history_cli_displays_metadata_without_raw_source_requirement(tmp_path, capsys):
    root = frozen_fixture(tmp_path)
    (tmp_path / "original-inventory.json").unlink()
    main(["history", str(root), "--json"])
    report = json.loads(capsys.readouterr().out)
    assert report["metadata_bindings_verified"]
    assert not report["source_inventory_present"]
    assert not report["full_city_data_reverified"]
    with pytest.raises(ValueError, match="source inventory"):
        verify_historical(root, report_dir=tmp_path / "audit")
